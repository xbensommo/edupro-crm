import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider';

export default defineCollection({
  name: 'clients',
  shard: { type: 'none' },
  schema: {
    clientNumber: { type: FIELD_TYPES.STRING, required: true, searchable: true, sortable: true, filterable: true },
    firstName: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    lastName: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    fullName: { type: FIELD_TYPES.STRING, required: true, searchable: true, sortable: true, filterable: true },
    phonePrimary: { type: FIELD_TYPES.STRING, required: true, searchable: true, filterable: true },
    phoneSecondary: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    email: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    gender: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    institutionName: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    studyLevel: { type: FIELD_TYPES.STRING, required: false, filterable: true, sortable: true },
    city: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    preferredContactMethod: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    defaultConsultantId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    tags: { type: FIELD_TYPES.ARRAY, required: false },
    status: { type: FIELD_TYPES.STRING, required: false, filterable: true, sortable: true },
    notes: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    lastEngagementAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true, filterable: true },
    createdBy: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
  },
  writableFields: [
    'clientNumber',
    'firstName',
    'lastName',
    'fullName',
    'phonePrimary',
    'phoneSecondary',
    'email',
    'gender',
    'institutionName',
    'studyLevel',
    'city',
    'preferredContactMethod',
    'defaultConsultantId',
    'tags',
    'status',
    'notes',
    'lastEngagementAt',
    'createdBy',
  ],
  updateableFields: [
    'firstName',
    'lastName',
    'fullName',
    'phonePrimary',
    'phoneSecondary',
    'email',
    'gender',
    'institutionName',
    'studyLevel',
    'city',
    'preferredContactMethod',
    'defaultConsultantId',
    'tags',
    'status',
    'notes',
    'lastEngagementAt',
  ],
  indexes: [
    { fields: ['clientNumber'] },
    { fields: ['phonePrimary'] },
    { fields: ['email'] },
    { fields: ['status', 'createdAt'] },
    { fields: ['defaultConsultantId', 'createdAt'] },
  ], 
  search: {
    mode: 'token-array',
    fields: ['clientNumber', 'firstName', 'lastName', 'fullName', 'phonePrimary', 'email', 'institutionName'],
  },
  rules: {
    read: 'auth',
    create: 'auth',
    update: 'auth',
    delete: 'adminOnly',
  },
});
