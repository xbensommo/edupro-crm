import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider'

/**
 * Finance source transactions before posting to the ledger.
 */
const financeTransactions = defineCollection({
  name: 'finance_transactions',
  shard: { type: 'monthly', field: 'occurredOn' },
  schema: {
    type: {
      type: FIELD_TYPES.STRING,
      required: true,
      filterable: true,
      sortable: true,
      enum: ['payment', 'expense', 'payout', 'adjustment'],
    },
    status: {
      type: FIELD_TYPES.STRING,
      required: true,
      filterable: true,
      sortable: true,
      enum: ['draft', 'reviewed', 'posted', 'reversed', 'cancelled'],
    },
    reference: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    memo: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    occurredOn: { type: FIELD_TYPES.TIMESTAMP, required: true, sortable: true, filterable: true },
    amount: { type: FIELD_TYPES.NUMBER, required: true, sortable: true, filterable: true },
    currency: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    clientId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    clientLabel: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    consultantId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    consultantLabel: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    sourceRef: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    accountOverrides: { type: FIELD_TYPES.OBJECT, required: false },
    lines: { type: FIELD_TYPES.ARRAY, required: false },
    postedJournalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    reversalJournalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    reviewedAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true },
    reviewedBy: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    postedAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true },
    postedBy: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    reversedAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true },
    createdBy: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, sortable: true },
  },
  writableFields: [
    'type',
    'status',
    'reference',
    'memo',
    'occurredOn',
    'amount',
    'currency',
    'clientId',
    'clientLabel',
    'consultantId',
    'consultantLabel',
    'sourceRef',
    'accountOverrides',
    'lines',
    'postedJournalEntryId',
    'reversalJournalEntryId',
    'reviewedAt',
    'reviewedBy',
    'postedAt',
    'postedBy',
    'reversedAt',
    'createdBy',
    'createdAt',
    'updatedAt',
  ],
  updateableFields: [
    'status',
    'reference',
    'memo',
    'occurredOn',
    'amount',
    'currency',
    'clientId',
    'clientLabel',
    'consultantId',
    'consultantLabel',
    'sourceRef',
    'accountOverrides',
    'lines',
    'postedJournalEntryId',
    'reversalJournalEntryId',
    'reviewedAt',
    'reviewedBy',
    'postedAt',
    'postedBy',
    'reversedAt',
    'createdAt',
    'updatedAt',
  ],
  indexes: [
    { fields: ['status', 'occurredOn'] },
    { fields: ['type', 'status', 'occurredOn'] },
    { fields: ['consultantId', 'status', 'occurredOn'] },
    { fields: ['clientId', 'status', 'occurredOn'] },
  ],
  search: {
    mode: 'token-array',
    fields: ['reference', 'memo', 'clientLabel', 'consultantLabel', 'sourceRef'],
  },
})

export default financeTransactions
