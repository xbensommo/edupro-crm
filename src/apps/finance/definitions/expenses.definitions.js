/**
 * @file finance/definitions/expenses.definitions.js
 * @description Business expenses and outgoing spend.
 */

import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider';

export default defineCollection({
  name: 'expenses',
  shard: { type: 'monthly', field: 'expenseDate' },
  schema: {
    expenseCode: { type: FIELD_TYPES.STRING, required: true, searchable: true, sortable: true, filterable: true },
    expenseDate: { type: FIELD_TYPES.TIMESTAMP, required: true, filterable: true, sortable: true },
    category: { type: FIELD_TYPES.STRING, required: true, filterable: true, sortable: true },
    description: { type: FIELD_TYPES.STRING, required: true, searchable: true },
    vendorName: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    amount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    currency: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    paymentMethod: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    referenceNumber: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    relatedUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    relatedEngagementId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    approvedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    recordedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    status: { type: FIELD_TYPES.STRING, required: false, filterable: true, sortable: true },
    receiptFileId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    journalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
  },
  writableFields: [
    'expenseCode',
    'expenseDate',
    'category',
    'description',
    'vendorName',
    'amount',
    'currency',
    'paymentMethod',
    'referenceNumber',
    'relatedUserId',
    'relatedEngagementId',
    'approvedByUserId',
    'recordedByUserId',
    'status',
    'receiptFileId',
    'journalEntryId',
  ],
  updateableFields: [
    'expenseDate',
    'category',
    'description',
    'vendorName',
    'amount',
    'currency',
    'paymentMethod',
    'referenceNumber',
    'relatedUserId',
    'relatedEngagementId',
    'approvedByUserId',
    'recordedByUserId',
    'status',
    'receiptFileId',
    'journalEntryId',
  ],
  indexes: [
    { fields: ['expenseCode'] },
    { fields: ['category', 'expenseDate'] },
    { fields: ['status', 'expenseDate'] },
    { fields: ['relatedEngagementId', 'expenseDate'] },
  ],
  search: {
    mode: 'token-array',
    fields: ['expenseCode', 'description', 'vendorName', 'referenceNumber'],
  },
  rules: {
    read: 'auth',
    create: 'financeOrAdmin',
    update: 'financeOrAdmin',
    delete: 'adminOnly',
  },
});
