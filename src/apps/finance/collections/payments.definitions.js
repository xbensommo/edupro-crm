/**
 * @file src/apps/finance/collections/payments.definitions.js
 * @description Client money received against engagements.
 */

import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider'

export default defineCollection({
  name: 'payments',
  shard: { type: 'none', field: 'paymentDate' },
  schema: {
    paymentCode: { type: FIELD_TYPES.STRING, required: true, immutable: true, searchable: true, sortable: true, filterable: true },
    clientId: { type: FIELD_TYPES.STRING, required: true, filterable: true },
    clientLabel: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    engagementId: { type: FIELD_TYPES.STRING, required: true, filterable: true },
    engagementCode: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    paymentType: { type: FIELD_TYPES.STRING, required: true, filterable: true, sortable: true },
    amount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    allocatedAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    unappliedAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    currency: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    paymentMethod: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    paymentDate: { type: FIELD_TYPES.TIMESTAMP, required: true, filterable: true, sortable: true },
    referenceNumber: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    receivedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    status: { type: FIELD_TYPES.STRING, required: false, filterable: true, sortable: true },
    proofFileId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    notes: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    journalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    financeTransactionId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    isDeleted: { type: FIELD_TYPES.BOOLEAN, readonly: true, system: true, filterable: true, default: false },
    deletedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
    deletedBy: { type: FIELD_TYPES.STRING, readonly: true, system: true, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
  },
  writableFields: [
    'paymentCode',
    'clientId',
    'clientLabel',
    'engagementId',
    'engagementCode',
    'paymentType',
    'amount',
    'allocatedAmount',
    'unappliedAmount',
    'currency',
    'paymentMethod',
    'paymentDate',
    'referenceNumber',
    'receivedByUserId',
    'status',
    'proofFileId',
    'notes',
    'journalEntryId',
    'financeTransactionId',
  ],
  updateableFields: [
    'clientLabel',
    'engagementCode',
    'paymentType',
    'amount',
    'allocatedAmount',
    'unappliedAmount',
    'currency',
    'paymentMethod',
    'paymentDate',
    'referenceNumber',
    'receivedByUserId',
    'status',
    'proofFileId',
    'notes',
    'journalEntryId',
    'financeTransactionId',
  ],
  primaryKey: { field: 'paymentCode', required: true },
  indexes: [
    { fields: ['paymentDate'], order: 'ASCENDING' },
    { fields: ['isDeleted', 'paymentDate'], order: 'ASCENDING' },
    { fields: ['paymentCode'], order: 'ASCENDING' },
    { fields: ['engagementId', 'paymentDate'], order: 'ASCENDING' },
    { fields: ['clientId', 'paymentDate'], order: 'ASCENDING' },
    { fields: ['status', 'paymentDate'], order: 'ASCENDING' },
    { fields: ['createdAt']},
  ],
  search: {
    mode: 'token-array',
    fields: ['paymentCode', 'referenceNumber', 'notes', 'clientLabel', 'engagementCode'],
  },
  rules: {
    read: 'auth',
    create: 'financeOrAdmin',
    update: 'financeOrAdmin',
    delete: 'financeOrAdmin',
  },
})
