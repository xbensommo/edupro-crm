/**
 * @file src/apps/finance/collections/invoices.definitions.js
 * @description Client invoices and receivables source documents.
 */

import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider'

export default defineCollection({
  name: 'invoices',
  shard: { type: 'none', field: 'issueDate' },
  schema: {
    invoiceCode: { type: FIELD_TYPES.STRING, required: true, immutable: true, searchable: true, sortable: true, filterable: true },
    clientId: { type: FIELD_TYPES.STRING, required: true, filterable: true },
    clientLabel: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    engagementId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    engagementCode: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    status: {
      type: FIELD_TYPES.STRING,
      required: true,
      filterable: true,
      sortable: true,
      enum: ['draft', 'issued', 'partially_paid', 'paid', 'overdue', 'cancelled'],
    },
    issueDate: { type: FIELD_TYPES.TIMESTAMP, required: true, filterable: true, sortable: true },
    dueDate: { type: FIELD_TYPES.TIMESTAMP, required: false, filterable: true, sortable: true },
    currency: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    subtotalAmount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    discountAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    taxAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    totalAmount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    allocatedAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    paidAmount: { type: FIELD_TYPES.NUMBER, required: false, filterable: true, sortable: true },
    balanceAmount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    lineItems: { type: FIELD_TYPES.ARRAY, required: false },
    notes: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    terms: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    sourceModule: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    sourceId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    financeTransactionId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    postedJournalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    issuedAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true, filterable: true },
    issuedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    cancelledAt: { type: FIELD_TYPES.TIMESTAMP, required: false, sortable: true },
    cancelledByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    cancellationReason: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    createdByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    isDeleted: { type: FIELD_TYPES.BOOLEAN, readonly: true, system: true, filterable: true, default: false },
    deletedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
    deletedBy: { type: FIELD_TYPES.STRING, readonly: true, system: true, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
  },
  writableFields: [
    'invoiceCode',
    'clientId',
    'clientLabel',
    'engagementId',
    'engagementCode',
    'status',
    'issueDate',
    'dueDate',
    'currency',
    'subtotalAmount',
    'discountAmount',
    'taxAmount',
    'totalAmount',
    'allocatedAmount',
    'paidAmount',
    'balanceAmount',
    'lineItems',
    'notes',
    'terms',
    'sourceModule',
    'sourceId',
    'financeTransactionId',
    'postedJournalEntryId',
    'issuedAt',
    'issuedByUserId',
    'cancelledAt',
    'cancelledByUserId',
    'cancellationReason',
    'createdByUserId',
  ],
  updateableFields: [
    'clientLabel',
    'engagementId',
    'engagementCode',
    'status',
    'issueDate',
    'dueDate',
    'currency',
    'subtotalAmount',
    'discountAmount',
    'taxAmount',
    'totalAmount',
    'allocatedAmount',
    'paidAmount',
    'balanceAmount',
    'lineItems',
    'notes',
    'terms',
    'sourceModule',
    'sourceId',
    'financeTransactionId',
    'postedJournalEntryId',
    'issuedAt',
    'issuedByUserId',
    'cancelledAt',
    'cancelledByUserId',
    'cancellationReason',
  ],
  primaryKey: { field: 'invoiceCode', required: true },
  indexes: [
    { fields: ['issueDate'], order: 'DESCENDING' },
    { fields: ['isDeleted', 'issueDate'], order: 'DESCENDING' },
    { fields: ['invoiceCode'], order: 'ASCENDING' },
    { fields: ['clientId', 'issueDate'], order: 'DESCENDING' },
    { fields: ['engagementId', 'issueDate'], order: 'DESCENDING' },
    { fields: ['status', 'dueDate'], order: 'ASCENDING' },
    { fields: ['status', 'issueDate'], order: 'DESCENDING' },
    { fields: ['isDeleted', 'createdAt'], order: 'DESCENDING' },
  ],
  search: {
    mode: 'token-array',
    fields: ['invoiceCode', 'clientLabel', 'engagementCode', 'notes', 'terms'],
  },
  rules: {
    read: 'auth',
    create: 'financeOrAdmin',
    update: 'financeOrAdmin',
    delete: 'financeOrAdmin',
  },
})
