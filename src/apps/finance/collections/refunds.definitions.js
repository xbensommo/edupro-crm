/**
 * @file src/apps/finance/collections/refunds.definitions.js
 * @description Refund requests and processed client refunds.
 */

import { FIELD_TYPES, defineCollection } from '@xbensommo/shard-provider'

export default defineCollection({
  name: 'refunds',
  shard: { type: 'none', field: 'refundDate' },
  schema: {
    refundCode: { type: FIELD_TYPES.STRING, required: true, searchable: true, sortable: true, filterable: true },
    clientId: { type: FIELD_TYPES.STRING, required: true, filterable: true },
    clientLabel: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    engagementId: { type: FIELD_TYPES.STRING, required: true, filterable: true },
    engagementCode: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    paymentId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    paymentCode: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    amount: { type: FIELD_TYPES.NUMBER, required: true, filterable: true, sortable: true },
    currency: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    reason: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    refundMethod: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    referenceNumber: { type: FIELD_TYPES.STRING, required: false, searchable: true, filterable: true },
    refundDate: { type: FIELD_TYPES.TIMESTAMP, required: true, filterable: true, sortable: true },
    approvedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    processedByUserId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    status: {
      type: FIELD_TYPES.STRING,
      required: false,
      filterable: true,
      sortable: true,
      enum: ['requested', 'approved', 'processed', 'cancelled'],
    },
    journalEntryId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    financeTransactionId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    isDeleted: { type: FIELD_TYPES.BOOLEAN, readonly: true, system: true, filterable: true, default: false },
    deletedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
    deletedBy: { type: FIELD_TYPES.STRING, readonly: true, system: true, filterable: true },
    createdAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true, filterable: true },
    updatedAt: { type: FIELD_TYPES.TIMESTAMP, readonly: true, system: true, sortable: true },
  },
  writableFields: [
    'refundCode',
    'clientId',
    'clientLabel',
    'engagementId',
    'engagementCode',
    'paymentId',
    'paymentCode',
    'amount',
    'currency',
    'reason',
    'refundMethod',
    'referenceNumber',
    'refundDate',
    'approvedByUserId',
    'processedByUserId',
    'status',
    'journalEntryId',
    'financeTransactionId',
  ],
  updateableFields: [
    'clientLabel',
    'engagementCode',
    'paymentId',
    'paymentCode',
    'amount',
    'currency',
    'reason',
    'refundMethod',
    'referenceNumber',
    'refundDate',
    'approvedByUserId',
    'processedByUserId',
    'status',
    'journalEntryId',
    'financeTransactionId',
  ],
  primaryKey: { field: 'refundCode', required: true },
  indexes: [
    { fields: ['refundCode'], order: 'ASCENDING' },
    { fields: ['refundDate'], order: 'ASCENDING' },
    { fields: ['isDeleted', 'refundDate'], order: 'ASCENDING' },
    { fields: ['engagementId', 'refundDate'], order: 'ASCENDING' },
    { fields: ['clientId', 'refundDate'], order: 'ASCENDING' },
    { fields: ['paymentId', 'refundDate'], order: 'ASCENDING' },
    { fields: ['status', 'refundDate'], order: 'ASCENDING' },
  ],
  search: {
    mode: 'token-array',
    fields: ['refundCode', 'reason', 'clientLabel', 'engagementCode', 'paymentCode', 'referenceNumber'],
  },
  rules: {
    read: 'auth',
    create: 'financeOrAdmin',
    update: 'financeOrAdmin',
    delete: 'adminOnly',
  },
})
