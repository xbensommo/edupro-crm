    publicUrl: { type: FIELD_TYPES.STRING, required: false },
    altText: { type: FIELD_TYPES.STRING, required: false, searchable: true },
    tags: { type: FIELD_TYPES.ARRAY, required: false },
    metadata: { type: FIELD_TYPES.MAP, required: false },
    visibility: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    sourceModule: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    clientId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    engagementId: { type: FIELD_TYPES.STRING, required: false, filterable: true },
    uploadedBy: { type: FIELD_TYPES.STRING, required: false, filterable: true },
